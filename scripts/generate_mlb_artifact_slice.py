"""Generate a bounded MLB fixture slice through the real artifact paths.

This script is intentionally narrow: it creates a deterministic, pregame-legal
MLB feature slice only when local production features are absent or `--force`
is provided, then calls the real candidate-comparison and validation services.
The resulting outputs are labeled as fixture/slice evidence, not production
model evidence.
"""

